// 교사 맞춤 이야기의 {teacher} {gift} {letter} 채우기
export function cleanStoryVars(v = {}) {
  const t = (x, n) => String(x ?? '').replace(/[{}<>]/g, '').trim().slice(0, n);
  return { teacher: t(v.teacher, 20), gift: t(v.gift, 30), letter: t(v.letter, 800) };
}
// 받침에 따라 을/를, 이/가, 은/는, 과/와 고르기 — '선물을(를)' → '선물을'
export function fixJosa(text) {
  // '설화보주(雪花寶珠)을(를)' 처럼 괄호가 붙어 있으면 괄호 앞 글자로 판단
  return String(text).replace(/([^\s(])((?:\([^()]*\))?)(을\(를\)|이\(가\)|은\(는\)|과\(와\))/g, (_, ch, paren, pair) => {
    const code = ch.charCodeAt(0);
    if (code < 0xac00 || code > 0xd7a3) return ch + paren + pair; // 한글이 아니면 그대로
    return ch + paren + ((code - 0xac00) % 28 ? pair[0] : pair[2]);
  });
}
function fill(obj, vars) {
  if (typeof obj === 'string') return fixJosa(obj.replace(/\{(teacher|gift|letter)\}/g, (_, k) => vars[k]));
  if (Array.isArray(obj)) return obj.map((x) => fill(x, vars));
  if (obj && typeof obj === 'object') return Object.fromEntries(Object.entries(obj).map(([k, x]) => [k, k === 'defaults' ? x : fill(x, vars)]));
  return obj;
}

export const STORY_IDS = Object.keys(STORIES);
export function getStory(id, vars) {
  const st = STORIES[id] || STORIES.seolhwa;
  if (!st.custom) return st;
  const v = cleanStoryVars(vars);
  const d = st.defaults;
  return fill(st, { teacher: v.teacher || d.teacher, gift: v.gift || d.gift, letter: v.letter || d.letter });
}
